// 외전은 그 던전이 열리는 순서대로 (다시 보기 목록·한꺼번에 볼 때). 본편 줄의 몇 번째 던전 뒤에 열리는지 + 거기서 몇 단계 더 들어가는지
(() => {
  const MAIN = ['forest', 'beach', 'crystal', 'plains', 'swamp', 'volcano', 'desert', 'frost', 'storm', 'dark', 'mine', 'canyon', 'sky', 'summit', 'meteor', 'ultra', 'areazero', 'zerodeep'];
  const order = id => {
    let d = dungeonById(id), depth = 0;
    while (d && !MAIN.includes(d.id) && depth < 20) { d = d.req ? dungeonById(d.req) : null; depth++; }
    return (d ? MAIN.indexOf(d.id) : MAIN.length) * 100 + depth;
  };
  const sides = SCENES.filter(sc => sc.side).sort((a, b) => order(a.dg) - order(b.dg));
  const main = SCENES.filter(sc => !sc.side);
  SCENES.splice(0, SCENES.length, ...main, ...sides);
})();
